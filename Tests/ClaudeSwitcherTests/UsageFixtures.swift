    /// A clock in PDT (UTC−7, which September and October 2026 are in): `"2026-09-22 19:16"`,
    /// optionally with seconds and a fraction (`"2026-09-26 20:59:59.716"`).
    static func pdt(_ text: String) -> Date {
        let parts = text.split(separator: " ")
        let day = parts[0].split(separator: "-").map { Int($0)! }
        let clock = parts[1].split(separator: ":")
        let seconds = clock.count > 2 ? Double(clock[2])! : 0
        let days = TranscriptReading.daysFromCivil(year: day[0], month: day[1], day: day[2])
        let local = Double(days * 86400 + Int(clock[0])! * 3600 + Int(clock[1])! * 60) + seconds
        return Date(timeIntervalSince1970: local + 7 * 3600)
    }

    static func samples(_ series: [(Int, Int, Int)], org: String, through end: Date? = nil) -> [UsageSample] {
        series.compactMap { row in
            let at = Date(timeIntervalSince1970: TimeInterval(row.0))
            if let end, at > end { return nil }
            return UsageSample(sampledAt: at, org: org, utilization: ["fh": row.1, "sd": row.2])
        }
    }

    static func personal(through end: Date? = nil) -> [UsageSample] { samples(personalSeries, org: "org-personal", through: end) }
    static func christy(through end: Date? = nil) -> [UsageSample] { samples(christySeries, org: "org-christy", through: end) }

    /// A ledger of single calls, `(time, spend, session, isSubagent)`, as the index would
    /// compose it: one ten-minute bucket per call, added up per session and per account.
    static func ledger(_ calls: [(at: Date, spend: Double)], session: String = "s1", subagent: Bool = false,
                       prompts: [Date] = [], anchors: [LimitAnchor] = [], indexedThrough: Date? = nil) -> ActivityLedger {
        var buckets = calls.map { call in
            ActivityLedger.Bucket(start: ActivityLedger.bucketStart(call.at), first: call.at, last: call.at, spend: call.spend,
                                  calls: 1, subagentCalls: subagent ? 1 : 0, subagentSpend: subagent ? call.spend : 0)
        }
        buckets += prompts.map {
            ActivityLedger.Bucket(start: ActivityLedger.bucketStart($0), first: $0, last: $0, spend: 0, calls: 0, prompts: 1)
        }
        return ActivityLedger(sessions: [session: buckets], anchors: anchors,
                              indexedThrough: indexedThrough ?? calls.map(\.at).max() ?? Date(timeIntervalSince1970: 0))
    }

