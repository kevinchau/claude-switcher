    /// A day of the week in PDT for a schedule's phase (0 = Sunday … 6 = Saturday) and the
    /// clock time as minutes past midnight.
    static func pdtWeekdayAndMinute(ofPhase phase: TimeInterval) -> (weekday: Int, minute: Int) {
        let local = phase - 7 * 3600
        let wrapped = (local.truncatingRemainder(dividingBy: 604_800) + 604_800).truncatingRemainder(dividingBy: 604_800)
        // The epoch fell on a Thursday.
        let day = Int(wrapped / 86400)
        return ((day + 4) % 7, Int(wrapped.truncatingRemainder(dividingBy: 86400) / 60))
    }

